# ============================================================================
# 参考绑定的说明文案（按图片序号逐个对号入座）
# ============================================================================

# ---- 3D站位图 参考型：4 张图（女形象 / 男形象 / 背景 / 纯人物站位）----
# ⚠️ 按用户定稿原文，名字后**不加空格**直接跟「场景参考」：
#      「作为North End 码头场景参考」（名字自带空格，模板不再添）
REF_ROLE_1 = {
    "形象参考": "作为 {name} 的形象参考",
    "场景参考": "作为{name}场景参考",
    "道具参考": "作为{name}的道具参考：画面中该道具的样式、颜色、材质、细节严格以这张图为准",
    "站位与机位参考": "作为本镜站位与机位参考：注意人物左右关系、朝向、间距、"
                      "以及镜头与被摄对象的相对关系",
}

# ---- 背景站位图 锁定型：3 张图（女形象 / 男形象 / 背景+人物融合）----
REF_ROLE_2 = {
    "形象参考": "作为 {name} 的形象参考",
    "背景锁定参考": "作为本镜背景与人物站位的锁定参考图：环境结构、光影、"
                    "以及两人的左右关系、朝向、间距，全部以这张图为准，"
                    "背景必须严格照搬，不得改变场景布局与光影",
}

HEAD = "@ 图片参考绑定（严格按序号对应）："

# 收尾（两条路共用）
TAIL = "两人衣着、发型、体态严格参照各自形象参考图，保持人物一致性。"


def build_prompt(route, refs, body):
    """★ 组装提示词。

    route : 1 或 2
    refs  : [(name, role), ...]  顺序 = @图片1..N
            · role 取值见 REF_ROLE_1 / REF_ROLE_2
            · 站位图/锁定图那项 name 传 ""（文案里不需要名字）
    body  : 分镜正文（场景描述 / 人物动作 / 站位描述）
    """
    table = REF_ROLE_1 if int(route) == 1 else REF_ROLE_2
    lines = []
    for i, (name, role) in enumerate(refs, 1):
        if role not in table:
            raise ValueError(
                f"{'3D站位图' if route == 1 else '背景站位图'} 不认识的角色类型 {role!r}；"
                f"可选：{list(table)}")
        tpl = table[role]
        lines.append(f"@图片{i} {tpl.format(name=name).strip()}")
    return HEAD + "\n" + "\n".join(lines) + "\n" + body.strip() + "\n" + TAIL


